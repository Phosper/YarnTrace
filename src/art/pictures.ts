const cache = new Map<string, Art>();

/** Rasterised, toned art for a picture at the given grid size (longest side). */
export function pictureArt(picture: Picture, size: number): Art {
  const n = Math.max(8, Math.min(48, Math.round(size)));
  const key = `${picture.id}@${n}`;
  let art = cache.get(key);
  if (!art) {
    art = toneGrid(rasterize(picture.shapes, n));
    cache.set(key, art);
  }
  return art;
}
